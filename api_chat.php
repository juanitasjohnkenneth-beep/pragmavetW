<?php
session_start();
include("dbconnection.php");

header('Content-Type: application/json');

if(!isset($_SESSION['user_id'])){
    echo json_encode(["error" => "Unauthorized"]);
    exit();
}

$current_user_id = (int)$_SESSION['user_id'];
$role = $_SESSION['role'] ?? 'client';
$is_clinic_staff = in_array($role, ['admin', 'doctor', 'staff', 'clinic_owner', 'owner']);

$action = $_POST['action'] ?? $_GET['action'] ?? '';

// Use a unified clinic admin ID so all clinic staff/admins share the same inbox for clients
$first_admin_query = $conn->query("SELECT id FROM users WHERE role='admin' ORDER BY id ASC LIMIT 1");
$admin_id = 1;
if($first_admin_query && $first_admin_query->num_rows > 0) {
    $admin_id = $first_admin_query->fetch_assoc()['id'];
}

if ($action === 'send') {
    $message = trim($_POST['message'] ?? '');
    $has_attachment = isset($_FILES['attachment']) && $_FILES['attachment']['error'] == UPLOAD_ERR_OK;
    
    if(empty($message) && !$has_attachment) { echo json_encode(["status"=>"empty"]); exit; }
    
    if (!$is_clinic_staff) {
        $sender = $current_user_id;
        $receiver = $admin_id; 
    } else {
        // Clinic Staff/Admin replying to specific client (Unified Inbox ID)
        $sender = $admin_id;
        $receiver = (int)$_POST['client_id'];
    }
    
    $attachment_url = null;
    $attachment_type = null;
    $attachment_name = null;
    
    if($has_attachment) {
        $upload_dir = 'uploads/chat/';
        if(!is_dir($upload_dir)) mkdir($upload_dir, 0777, true);
        
        $file = $_FILES['attachment'];
        $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));

        // Only photos, videos and PDFs, checked by their real content (not just the name), up to 10 MB
        $allowed = [
            'jpg' => ['image/jpeg'], 'jpeg' => ['image/jpeg'], 'png' => ['image/png'], 'gif' => ['image/gif'], 'webp' => ['image/webp'],
            'mp4' => ['video/mp4'], 'webm' => ['video/webm'], 'pdf' => ['application/pdf'],
        ];
        $mime = (new finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']);
        if (!isset($allowed[$ext]) || !in_array($mime, $allowed[$ext], true) || $file['size'] > 10 * 1024 * 1024) {
            echo json_encode(["status" => "error", "error" => "Only photos (JPG, PNG, GIF, WEBP), videos (MP4, WEBM) or PDF files up to 10 MB can be sent."]);
            exit();
        }
        $new_name = bin2hex(random_bytes(8)) . '_' . time() . '.' . $ext;
        $target = $upload_dir . $new_name;
        
        if(in_array($ext, ['jpg', 'jpeg', 'png', 'gif', 'webp'])) {
            $attachment_type = 'image';
        } elseif(in_array($ext, ['mp4', 'webm'])) {
            $attachment_type = 'video';
        } else {
            $attachment_type = 'file';
        }
        
        if(move_uploaded_file($file['tmp_name'], $target)) {
            $attachment_url = $target;
            $attachment_name = $file['name'];
        }
    }
    
    $stmt = $conn->prepare("INSERT INTO chat_messages(sender_id, receiver_id, message, attachment_url, attachment_type, attachment_name) VALUES(?,?,?,?,?,?)");
    $stmt->bind_param("iissss", $sender, $receiver, $message, $attachment_url, $attachment_type, $attachment_name);
    if($stmt->execute()) {
        echo json_encode(["status" => "success"]);
    } else {
        echo json_encode(["status" => "error", "error" => $conn->error]);
    }
    exit();
} 

elseif ($action === 'fetch') {
    if (!$is_clinic_staff) {
        $client_id = $current_user_id;
        $admin_role_id = $admin_id; 
    } else {
        $client_id = (int)$_GET['client_id'];
        $admin_role_id = $admin_id; // Unified Inbox
    }

    // Mark as read if fetched by recipient
    if (!$is_clinic_staff) {
        $conn->query("UPDATE chat_messages SET is_read=1 WHERE receiver_id=$current_user_id AND sender_id=$admin_role_id");
    } else {
        $conn->query("UPDATE chat_messages SET is_read=1 WHERE receiver_id=$admin_role_id AND sender_id=$client_id");
    }

    $q = $conn->prepare("SELECT c.*, u.fullname as sender_name FROM chat_messages c JOIN users u ON c.sender_id = u.id WHERE (c.sender_id=? AND c.receiver_id=?) OR (c.sender_id=? AND c.receiver_id=?) ORDER BY c.created_at ASC");
    $q->bind_param("iiii", $client_id, $admin_role_id, $admin_role_id, $client_id);
    $q->execute();
    $res = $q->get_result();
    
    $msgs = [];
    while($row = $res->fetch_assoc()) {
        $raw_msg = $row['message'] ?? '';
        // If message is a system notification generated by the backend, bypass HTML escaping to preserve UI buttons
        if (strpos($raw_msg, 'Admin Notice:') === 0 && strpos($raw_msg, '<a href') !== false && $row['sender_id'] == $admin_role_id) {
            $msg_text = $raw_msg;
        } else {
            $msg_text = htmlspecialchars($raw_msg);
        }

        $msgs[] = [
            'id' => $row['id'],
            'message' => $msg_text,
            'attachment_url' => $row['attachment_url'],
            'attachment_type' => $row['attachment_type'],
            'attachment_name' => htmlspecialchars($row['attachment_name'] ?? ''),
            'is_me' => ((!$is_clinic_staff) ? ($row['sender_id'] == $current_user_id) : ($row['sender_id'] == $admin_role_id)),
            'sender_name' => ($row['sender_id'] == $admin_role_id) ? "Clinic Front Desk" : htmlspecialchars($row['sender_name']),
            'time' => date("h:i A", strtotime($row['created_at'])),
            'date' => date("Y-m-d", strtotime($row['created_at']))
        ];
    }
    echo json_encode($msgs);
    exit();
}

elseif ($action === 'conversations' && $is_clinic_staff) {
    // Clinic inbox: one row per client, newest activity first
    $rows = [];
    $q = $conn->query("
        SELECT u.id, u.fullname, u.profile_picture,
               (SELECT COUNT(*) FROM chat_messages x WHERE x.sender_id = u.id AND x.receiver_id = $admin_id AND x.is_read = 0) AS unread,
               lm.message AS last_message, lm.attachment_type AS last_attachment, lm.sender_id AS last_sender, lm.created_at AS last_at
        FROM (SELECT IF(sender_id = $admin_id, receiver_id, sender_id) AS cid, MAX(id) AS last_id
              FROM chat_messages WHERE sender_id = $admin_id OR receiver_id = $admin_id GROUP BY cid) t
        JOIN users u ON u.id = t.cid
        JOIN chat_messages lm ON lm.id = t.last_id
        WHERE IFNULL(u.role, '') NOT IN ('admin', 'doctor', 'staff', 'clinic_owner', 'owner')
        ORDER BY t.last_id DESC
    ");
    if ($q) while ($r = $q->fetch_assoc()) {
        $preview = trim(strip_tags($r['last_message'] ?? ''));
        if ($preview === '' && $r['last_attachment']) $preview = $r['last_attachment'] === 'image' ? 'Photo' : ($r['last_attachment'] === 'video' ? 'Video' : 'Attachment');
        $rows[] = [
            'id' => (int)$r['id'],
            'name' => htmlspecialchars($r['fullname']),
            'picture' => $r['profile_picture'] ? htmlspecialchars($r['profile_picture']) : null,
            'unread' => (int)$r['unread'],
            'preview' => htmlspecialchars(mb_substr($preview, 0, 90)),
            'from_clinic' => (int)$r['last_sender'] === (int)$admin_id,
            'at' => $r['last_at'],
        ];
    }
    echo json_encode($rows);
    exit();
}

elseif ($action === 'clients' && $is_clinic_staff) {
    // Start a new conversation: search pet owners by name or email
    $term = '%' . trim($_GET['q'] ?? '') . '%';
    $st = $conn->prepare("SELECT id, fullname, email FROM users WHERE role IN ('client', 'user') AND (fullname LIKE ? OR email LIKE ?) ORDER BY fullname LIMIT 12");
    $st->bind_param("ss", $term, $term);
    $st->execute();
    $out = [];
    $res = $st->get_result();
    while ($r = $res->fetch_assoc()) $out[] = ['id' => (int)$r['id'], 'name' => htmlspecialchars($r['fullname']), 'email' => htmlspecialchars($r['email'] ?? '')];
    echo json_encode($out);
    exit();
}

elseif ($action === 'unread_count') {
    // For client floating widget and global unread
    $target_id = (!$is_clinic_staff) ? $current_user_id : $admin_id;
    $c = $conn->query("SELECT COUNT(*) as unread FROM chat_messages WHERE receiver_id=$target_id AND is_read=0")->fetch_assoc();
    echo json_encode(["unread" => $c['unread']]);
    exit();
}
?>
